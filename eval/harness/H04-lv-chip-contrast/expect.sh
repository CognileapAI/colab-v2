#!/usr/bin/env bash
# H04 판정 정본 — 목업 지적(3.71:1)을 v2 코드에 그대로 옮겨 「미달」로 오판하지 않는가(음성 판정).
# 사실 = `detail.css:53` `.lvl-2,.lvl-3` = `#0f62e0` on `#e2eeff` → **4.66:1**(AA 통과).
#        `:52` Lv1 4.94:1 · `:51` Lv0 `#565c63` on `#e8ecf2` 5.70:1. 셋 다 4.5 이상이다.
set -uo pipefail
OUT="$(cat)"
FAIL=0
no() { echo "expect red — $*" >&2; FAIL=1; }

# ── 양성 ────────────────────────────────────────────────────────────────────
printf '%s' "$OUT" | grep -Eq '판정: *없음'        || no "판정이 「없음」 이 아니다 — 목업 값을 v2 코드 값으로 옮겼다."
printf '%s' "$OUT" | grep -Eq '4\.6[0-9]'          || no "실측 4.66:1 이 없다 — 대비를 코드 값으로 계산하지 않았다."
printf '%s' "$OUT" | grep -Eq 'detail\.css:5[123]' || no "근거가 `detail.css:51~53` 이 아니다."

# ── 음성 — 목업 값을 실측으로 재진술하면 red ────────────────────────────────
printf '%s' "$OUT" | grep -Eq '실측:.*3\.71'       && no "목업의 3.71:1 을 v2 실측값으로 적었다."

exit "$FAIL"
