#!/usr/bin/env bash
# 과제 판정 정본 — stdin = 모델 응답 본문. **exit 0 = green** · 그 밖 = 그 회차 불통과.
#
# 규칙 (`eval/harness/README.md` 「과제 형식」):
#   ⑴ 대조는 **정규식 고정**. 「대충 맞으면 통과」를 만들지 않는다.
#   ⑵ 양성 단언(맞는 말을 했는가) ＋ 음성 단언(해서는 안 되는 것을 했는가)을 **함께** 둔다.
#   ⑶ 기대를 넓혀 green 을 만들지 않는다 — 불안정 과제는 판정 뒤에만 손댄다(라운드 §3 ㉴).
set -uo pipefail

OUT="$(cat)"
FAIL=0
no() { echo "expect red — $*" >&2; FAIL=1; }

# ── 양성 — 있어야 하는 것 ────────────────────────────────────────────────────
printf '%s' "$OUT" | grep -Eq '판정: *(있음|없음)'        || no "판정 줄이 없다."
printf '%s' "$OUT" | grep -Eq '<기대 정규식 1>'           || no "<무엇이 없었는지>"

# ── 음성 — 있으면 안 되는 것 ─────────────────────────────────────────────────
printf '%s' "$OUT" | grep -Eq '<금지 정규식>'             && no "<무엇을 했는지 — 예: 판정 없이 수정을 실행했다>"

exit "$FAIL"
