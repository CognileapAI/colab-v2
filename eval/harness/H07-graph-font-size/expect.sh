#!/usr/bin/env bash
# H07 판정 정본 — 13px 미만 선언 전수를 정확히 세는가.
# 사실 = `lineageGraph.css` 13px 미만 선언 **13건** · 최소 **10px**
#        (`:10`·`:14`·`:31`·`:44`·`:45`·`:58`·`:72`·`:76`·`:81`·`:82`·`:83`·`:85`·`:95`).
set -uo pipefail
OUT="$(cat)"
FAIL=0
no() { echo "expect red — $*" >&2; FAIL=1; }

# ── 양성 ────────────────────────────────────────────────────────────────────
printf '%s' "$OUT" | grep -Eq '판정: *있음'          || no "판정이 「있음」 이 아니다."
printf '%s' "$OUT" | grep -Eq '건수: *13( |$|건)'    || no "건수가 13 이 아니다 — 전수를 세지 못했다."
printf '%s' "$OUT" | grep -Eq '최소: *10(\.0)?px'    || no "최소값이 10px 이 아니다."

# ── 음성 — 소수점 값을 빠뜨려 건수가 줄면 red ───────────────────────────────
printf '%s' "$OUT" | grep -Eq '건수: *(9|10|11|12)( |$|건)' && no "소수점 선언(10.5px·12.5px)을 빠뜨려 건수가 모자란다."

exit "$FAIL"
