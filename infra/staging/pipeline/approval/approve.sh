#!/usr/bin/env bash
# 승인 기록 — **자동 판정이 아니라 사람의 기록**이다 (`㊵` · `〈168〉-㉴`).
#
#   approve.sh <승인자> <무엇을 눈으로 봤는가>
#
# 기록 자리 = **릴리스 원장과 같은 파일 · 같은 형식**(`〈168〉-㉴`).
# 근거 — 승인과 배포는 같은 사건의 앞뒤다. 파일이 갈리면 「무엇을 승인했고 무엇이 나갔나」의
# 대조가 어려워지고, 대조가 어려우면 승인 기록은 곧 안 읽힌다.
#
# 승인자 표기 = **사람 이름 한 낱말**(예: `Ted`). 계정 ID·이메일을 쓰지 않는다 —
# 원장은 호스트 위 평문이고 `〈93〉` 비밀 취급의 대상을 늘리지 않는다.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$HERE/../lib.sh"

WHO="${1:-}"; SAW="${2:-}"

# ⭑ 세 상태 — 값이 있으면 기록한다 / 면제는 없다 / **비면 실패한다.**
#   `㊵`-③ 이 「승인 단위는 WU 가 아니라 눈으로 확인 가능한 화면·흐름」이라 적었으므로
#   「무엇을 눈으로 봤는가」 칸은 **비울 수 없다.** 빈 승인은 승인이 아니다.
if [ -z "$WHO" ]; then
  echo "거부: 승인자가 비었다. 사람 이름 한 낱말(예: Ted)." >&2; exit 64
fi
case "$WHO" in
  *[[:space:]]*) echo "거부: 승인자는 한 낱말이다 — '$WHO'" >&2; exit 64 ;;
  *@*)           echo "거부: 이메일·계정 ID 를 쓰지 않는다 (〈93〉 · 〈168〉-㉴)" >&2; exit 64 ;;
esac
if [ -z "$SAW" ]; then
  echo "거부: 「무엇을 눈으로 봤는가」가 비었다. ㊵-③ — 승인 단위는 화면·흐름이다." >&2; exit 64
fi
case "$SAW" in *$'\t'*) echo "거부: 탭 문자를 쓸 수 없다(원장이 탭 구분이다)" >&2; exit 64 ;; esac

SHA="$(git -C "$HERE/../../../.." rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
ledger_append approve "$SHA" "-" "-" "승인자=$WHO 본것=$SAW"
echo "승인 기록됨 — $(ledger_path)"
tail -n 1 "$(ledger_path)"
